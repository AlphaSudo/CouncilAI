"""Generate request DTO types from the same Pydantic schemas as the API."""

import json
from pathlib import Path
from zerowall import contracts


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(x) for x in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return "(" + ts(schema.get("items", {})) + ")[]"
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            return (
                "{ "
                + "; ".join(
                    json.dumps(k) + ("" if k in required else "?") + ": " + ts(v)
                    for k, v in schema["properties"].items()
                )
                + " }"
            )
        additional = schema.get("additionalProperties", {})
        return (
            "Record<string, "
            + (ts(additional) if isinstance(additional, dict) else "unknown")
            + ">"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


schemas = {}
for name in dir(contracts):
    cls = getattr(contracts, name)
    if (
        isinstance(cls, type)
        and issubclass(cls, contracts.Contract)
        and cls is not contracts.Contract
    ):
        schema = cls.model_json_schema()
        schemas.update(schema.get("$defs", {}))
        schemas[name] = schema
target = Path(__file__).resolve().parents[1] / "apps/web/src/contracts.generated.ts"
target.write_text(
    "// Generated by scripts/generate_types.py; edit Python contracts instead.\n"
    + "\n".join(
        "export type " + name + " = " + ts(schema) + ";"
        for name, schema in sorted(schemas.items())
    )
    + "\n",
    encoding="utf-8",
)
print(f"Generated {len(schemas)} shared request types.")
